-- Execute no SQL Editor do Supabase. Cadastre somente gols conferidos.
create table if not exists public.goals (
 id bigint generated by default as identity primary key,
 source_event_id text unique,
 date date not null,
 team text not null,
 opponent text not null,
 competition text not null,
 body_part text not null check (body_part in ('right','left','head','other','unknown')),
 method text not null default 'Bola rolando',
 minute integer check (minute >= 0 and minute <= 150),
 title text not null,
 highlight_url text check (highlight_url is null or highlight_url ~ '^https://'),
 source_url text check (source_url is null or source_url ~ '^https://')
);
alter table public.goals enable row level security;
-- Sem políticas públicas: apenas o backend com chave de servidor lê os dados.

-- Votos da comunidade ("Ajude a classificar") para gols com body_part = 'unknown'.
-- Os votos não alteram goals.body_part. O consenso é conferido com fonte antes de virar classificação oficial.
-- voter_hash e ip_hash são HMAC-SHA256 com VOTE_SECRET: o banco não guarda cookie nem IP.
create table if not exists public.goal_votes (
 id bigint generated by default as identity primary key,
 goal_id bigint not null references public.goals(id) on delete cascade,
 body_part text not null check (body_part in ('right','left','head')),
 voter_hash text not null check (voter_hash ~ '^[a-f0-9]{64}$'),
 ip_hash text not null check (ip_hash ~ '^[a-f0-9]{64}$'),
 created_at timestamptz not null default now(),
 unique (goal_id, voter_hash)
);
create index if not exists goal_votes_goal_idx on public.goal_votes (goal_id);
create index if not exists goal_votes_ip_time_idx on public.goal_votes (ip_hash, created_at);
alter table public.goal_votes enable row level security;
