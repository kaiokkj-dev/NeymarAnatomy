create table if not exists public.goals (
 id bigint generated by default as identity primary key,
 date date not null,
 team text not null,
 opponent text not null,
 competition text not null,
 body_part text not null check (body_part in ('right','left','head','other','unknown')),
 method text not null default 'Bola rolando',
 minute integer check (minute >= 0 and minute <= 150),
 title text not null,
 highlight_url text check (highlight_url is null or highlight_url ~ '^https://'),
 source_url text check (source_url is null or source_url ~ '^https://')
);
alter table public.goals enable row level security;
